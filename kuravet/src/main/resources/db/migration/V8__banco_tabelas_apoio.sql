-- SEQ_CONSULTA nasce em 11 (V1) e a aplicacao a compartilha: sem este ajuste,
-- a ~40a consulta criada pelo app colidiria com os IDs 50-57 da demonstracao.
-- Avanca a sequence para acima de qualquer ID existente (minimo 100).
DECLARE
    v_alvo  NUMBER;
    v_atual NUMBER;
BEGIN
    SELECT GREATEST(100, NVL(MAX(ID_CONSULTA), 0) + 1) INTO v_alvo FROM CONSULTA;
    SELECT SEQ_CONSULTA.NEXTVAL INTO v_atual FROM DUAL;

    IF v_atual < v_alvo THEN
        EXECUTE IMMEDIATE 'ALTER SEQUENCE SEQ_CONSULTA INCREMENT BY ' || (v_alvo - v_atual);
        SELECT SEQ_CONSULTA.NEXTVAL INTO v_atual FROM DUAL;
        EXECUTE IMMEDIATE 'ALTER SEQUENCE SEQ_CONSULTA INCREMENT BY 1';
    END IF;
END;
/

COMMIT;
